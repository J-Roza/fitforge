List<Exercise> getExercisesByMuscle(MuscleGroup muscle) =>
    allExercises.where((e) => e.primaryMuscle == muscle).toList();

List<Exercise> getExercisesByRole(ExerciseRole role) =>
    allExercises.where((e) => e.role == role).toList();

List<Exercise> searchExercises(String query) {
  final q = query.toLowerCase();
  return allExercises.where((e) =>
      e.name.toLowerCase().contains(q) ||
      e.primaryMuscle.label.toLowerCase().contains(q) ||
      e.description.toLowerCase().contains(q)).toList();
}
